#!/usr/bin/env bash
# Regenerates versions.lock from the monorepo's own root pnpm-lock.yaml and
# package.json, so the Containerfile's toolchain pins (Playwright's ffmpeg,
# pnpm) can be checked against the repository instead of drifting as a
# second, hand-maintained source of truth.
# versions.lock is generated output: never hand-edit it, rerun this script.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
ROOT_PACKAGE_JSON="$REPO_ROOT/package.json"
ROOT_LOCKFILE="$REPO_ROOT/pnpm-lock.yaml"
VERSIONS_LOCK="$SCRIPT_DIR/versions.lock"

require_sources() {
  if [[ ! -f "$ROOT_LOCKFILE" ]]; then
    echo "lock-versions.sh: missing $ROOT_LOCKFILE" >&2
    exit 1
  fi
  if [[ ! -f "$ROOT_PACKAGE_JSON" ]]; then
    echo "lock-versions.sh: missing $ROOT_PACKAGE_JSON" >&2
    exit 1
  fi
}

resolve_playwright_version() {
  local versions
  versions="$(grep -oE "^  '@playwright/test@[0-9][^']*':" "$ROOT_LOCKFILE" \
    | sed -E "s/^  '@playwright\/test@([^']*)':/\1/" \
    | sort -u)"
  local count
  count="$(printf '%s\n' "$versions" | grep -c .)"
  if [[ "$count" -eq 0 ]]; then
    echo "lock-versions.sh: no @playwright/test version found in $ROOT_LOCKFILE" >&2
    exit 1
  fi
  if [[ "$count" -gt 1 ]]; then
    echo "lock-versions.sh: multiple @playwright/test versions found in $ROOT_LOCKFILE, cannot pick one:" >&2
    printf '%s\n' "$versions" >&2
    exit 1
  fi
  printf '%s' "$versions"
}

resolve_pnpm_version() {
  # Empty when the root package.json sets no packageManager field — the
  # contract then allows one pinned version stated in the Containerfile.
  node -e "
    const pkg = require('$ROOT_PACKAGE_JSON');
    const pm = pkg.packageManager || '';
    const match = /^pnpm@(.+)$/.exec(pm);
    process.stdout.write(match ? match[1] : '');
  "
}

main() {
  require_sources
  local playwright_version pnpm_version
  playwright_version="$(resolve_playwright_version)"
  pnpm_version="$(resolve_pnpm_version)"
  {
    echo "# Generated by containers/saturday-runner/lock-versions.sh — do not hand-edit."
    echo "# Regenerate with: containers/saturday-runner/lock-versions.sh"
    echo "PLAYWRIGHT_VERSION=$playwright_version"
    echo "PNPM_VERSION=$pnpm_version"
  } >"$VERSIONS_LOCK"
  echo "lock-versions.sh: wrote PLAYWRIGHT_VERSION=$playwright_version PNPM_VERSION=$pnpm_version to $VERSIONS_LOCK"
}

main "$@"
