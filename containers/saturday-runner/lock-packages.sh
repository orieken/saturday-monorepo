#!/usr/bin/env bash
# Regenerates apt.lock from packages.list by resolving the real dependency
# closure (every package apt would install, not just the top-level names)
# against the pinned base image and the vendored Chrome/Edge repositories.
# apt.lock is generated output: never hand-edit it, rerun this script.
#
# With --ubi9, regenerates rpm.lock and rpms/ from rpm-packages.list instead
# (see lock_ubi9 below).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BASE_IMAGE="node:24.19.0-bookworm-slim@sha256:a9f5f7c91a432850b2a8a7797adf5eadb6c733ceed61167806cee7ea7fbc29df"
PACKAGES_LIST="$SCRIPT_DIR/packages.list"
APT_LOCK="$SCRIPT_DIR/apt.lock"
KEYS_DIR="$SCRIPT_DIR/keys"
BOOTSTRAP_PACKAGES="ca-certificates gnupg"

require_packages_list() {
  if [[ ! -f "$PACKAGES_LIST" ]]; then
    echo "lock-packages.sh: missing $PACKAGES_LIST" >&2
    exit 1
  fi
}

resolve_closure() {
  local packages="$1"
  docker run --rm --platform linux/amd64 \
    -v "$KEYS_DIR:/keys:ro" \
    -e "PACKAGES=$packages" \
    -e "BOOTSTRAP_PACKAGES=$BOOTSTRAP_PACKAGES" \
    "$BASE_IMAGE" bash -lc '
      set -euo pipefail
      apt-get update -qq
      # shellcheck disable=SC2086
      apt-get install -y -qq --no-install-recommends $BOOTSTRAP_PACKAGES >/dev/null
      for pkg in $BOOTSTRAP_PACKAGES; do
        echo "PIN $pkg=$(dpkg-query -W -f="\${Version}" "$pkg")"
      done
      cd /tmp
      cp /keys/google.asc /keys/microsoft.asc /keys/SHA256SUMS .
      sha256sum -c SHA256SUMS
      mkdir -p /usr/share/keyrings
      gpg --dearmor -o /usr/share/keyrings/google-chrome.gpg google.asc
      gpg --dearmor -o /usr/share/keyrings/microsoft.gpg microsoft.asc
      echo "deb [arch=amd64 signed-by=/usr/share/keyrings/google-chrome.gpg] https://dl.google.com/linux/chrome/deb/ stable main" > /etc/apt/sources.list.d/google-chrome.list
      echo "deb [arch=amd64 signed-by=/usr/share/keyrings/microsoft.gpg] https://packages.microsoft.com/repos/edge stable main" > /etc/apt/sources.list.d/microsoft-edge.list
      apt-get update -qq
      # shellcheck disable=SC2086
      apt-get install -y --no-install-recommends -s $PACKAGES
    '
}

write_lock() {
  local resolved="$1"
  if [[ -z "$resolved" ]]; then
    echo "lock-packages.sh: resolved package list is empty" >&2
    exit 1
  fi
  {
    echo "# Generated by containers/saturday-runner/lock-packages.sh — do not hand-edit."
    echo "# Regenerate with: containers/saturday-runner/lock-packages.sh"
    printf '%s\n' "$resolved"
  } >"$APT_LOCK"
}

# --- ubi9 -------------------------------------------------------------------
UBI9_IMAGE="registry.access.redhat.com/ubi9/ubi:9.6@sha256:dec374e05cc13ebbc0975c9f521f3db6942d27f8ccdf06b180160490eef8bdbc"
RPM_PACKAGES_LIST="$SCRIPT_DIR/rpm-packages.list"
RPM_LOCK="$SCRIPT_DIR/rpm.lock"
RPMS_DIR="$SCRIPT_DIR/rpms"
REPOS_DIR="$SCRIPT_DIR/repos"

# Installs the list in a throwaway UBI9 container and prints every package
# that is new or upgraded relative to the base image, as "<repo> <nevra>".
resolve_ubi9_closure() {
  local packages="$1"
  docker run --rm --platform linux/amd64 \
    -v "$KEYS_DIR:/keys:ro" -v "$REPOS_DIR:/repos:ro" -v "$RPMS_DIR:/rpms" \
    -e "PACKAGES=$packages" \
    "$UBI9_IMAGE" bash -lc '
      set -euo pipefail
      cd /keys && sha256sum -c SHA256SUMS.ubi9 >&2
      cp /keys/centos-official.asc /etc/pki/rpm-gpg/RPM-GPG-KEY-CentOS-Official
      cp /keys/epel9.asc /etc/pki/rpm-gpg/RPM-GPG-KEY-EPEL-9
      cp /keys/google.asc /keys/microsoft.asc /etc/pki/rpm-gpg/
      rpm --import /etc/pki/rpm-gpg/RPM-GPG-KEY-CentOS-Official /etc/pki/rpm-gpg/RPM-GPG-KEY-EPEL-9 \
        /etc/pki/rpm-gpg/google.asc /etc/pki/rpm-gpg/microsoft.asc
      cp /repos/stream.repo /repos/browsers.repo /repos/epel.repo /etc/yum.repos.d/
      sed -i "/^\[/a excludepkgs=mesa*" /etc/yum.repos.d/ubi.repo
      rpm -qa --qf "%{NAME}-%{EPOCH}:%{VERSION}-%{RELEASE}.%{ARCH}\n" | sed "s/-(none):/-0:/" | sort >/tmp/before
      # shellcheck disable=SC2086
      dnf --disableplugin=subscription-manager install -y -q $PACKAGES >&2
      rpm -qa --qf "%{NAME}-%{EPOCH}:%{VERSION}-%{RELEASE}.%{ARCH}\n" | sed "s/-(none):/-0:/" | sort >/tmp/after
      comm -13 /tmp/before /tmp/after >/tmp/added
      dnf --disableplugin=subscription-manager repoquery --installed -q \
        --qf "%{from_repo} %{name}-%{epoch}:%{version}-%{release}.%{arch}" 2>/dev/null \
        | grep -F -f /tmp/added
      EPEL="$(dnf --disableplugin=subscription-manager repoquery --installed -q \
        --qf "%{from_repo} %{name}-%{version}-%{release}.%{arch}" 2>/dev/null | awk "\$1==\"epel\" { print \$2 }")"
      rm -f /rpms/*.rpm
      # shellcheck disable=SC2086
      dnf --disableplugin=subscription-manager download -q --destdir /rpms $EPEL >&2
      rpm -K /rpms/*.rpm >&2
    '
}

write_ubi9_outputs() {
  local resolved="$1"
  local locked
  locked="$(printf '%s\n' "$resolved" | awk '$1 != "epel" { print $2 }' | sort -u)"
  if [[ -z "$locked" ]]; then
    echo "lock-packages.sh: resolved ubi9 package list is empty" >&2
    exit 1
  fi
  {
    echo "# Generated by containers/saturday-runner/lock-packages.sh --ubi9 — do not hand-edit."
    echo "# Regenerate with: containers/saturday-runner/lock-packages.sh --ubi9"
    printf '%s\n' "$locked"
  } >"$RPM_LOCK"
  (cd "$RPMS_DIR" && shasum -a 256 ./*.rpm | sed 's| \./| |' >SHA256SUMS)
  echo "lock-packages.sh: wrote $(printf '%s\n' "$locked" | grep -c .) pins to $RPM_LOCK and $(ls "$RPMS_DIR"/*.rpm | wc -l | tr -d ' ') EPEL RPMs to $RPMS_DIR"
}

lock_ubi9() {
  if [[ ! -f "$RPM_PACKAGES_LIST" ]]; then
    echo "lock-packages.sh: missing $RPM_PACKAGES_LIST" >&2
    exit 1
  fi
  mkdir -p "$RPMS_DIR"
  local packages
  packages="$(grep -v '^[[:space:]]*#' "$RPM_PACKAGES_LIST" | grep -v '^[[:space:]]*$' | tr '\n' ' ')"
  write_ubi9_outputs "$(resolve_ubi9_closure "$packages")"
}

main() {
  if [[ "${1:-}" == "--ubi9" ]]; then
    lock_ubi9
    return
  fi
  require_packages_list
  local packages
  packages="$(grep -v '^[[:space:]]*#' "$PACKAGES_LIST" | grep -v '^[[:space:]]*$' | tr '\n' ' ')"
  local raw resolved bootstrap_pins count
  raw="$(resolve_closure "$packages")"
  bootstrap_pins="$(printf '%s\n' "$raw" | awk '/^PIN / { print $2 }')"
  resolved="$(printf '%s\n' "$raw" | awk '
    /^Inst / {
      pkg = $2
      for (i = 3; i <= NF; i++) {
        if ($i ~ /^\(/) {
          ver = $i
          sub(/^\(/, "", ver)
          sub(/\)$/, "", ver)
          print pkg "=" ver
          break
        }
      }
    }
  '; printf '%s\n' "$bootstrap_pins")"
  resolved="$(printf '%s\n' "$resolved" | sort -u)"
  write_lock "$resolved"
  count="$(printf '%s\n' "$resolved" | grep -c .)"
  echo "lock-packages.sh: wrote $count pins to $APT_LOCK"
}

main "$@"
